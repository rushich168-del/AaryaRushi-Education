import {test} from 'node:test'
import assert from 'node:assert/strict'
import {randomUUID} from 'node:crypto'
import {createLocalKscDb} from './lib/local-draft-db.mjs'
test('creator provisioning, scope, lifecycle, identity preservation and academic denial on disposable PostgreSQL',async()=>{
 const db=await createLocalKscDb()
 try{
  await db.pool.query("ALTER TABLE auth.users ADD COLUMN IF NOT EXISTS email_confirmed_at timestamptz, ADD COLUMN IF NOT EXISTS raw_app_meta_data jsonb DEFAULT '{}'")
  db.applyMigration('202610020036_staff_accounts.sql')
  const admin=db.teacher,teacher=db.otherTeacher,creator=randomUUID(),existing=randomUUID(),request=randomUUID(),exam=db.catalogue.examId
  await db.pool.query("UPDATE ksc_staff_access SET role=CASE WHEN user_id=$1 THEN 'admin' ELSE 'teacher' END,state='active',password_change_required=false",[admin])
  db.applyMigration('202610020037_creator_accounts.sql')
  const rpc=(id,name,args={})=>db.runner.rpc(id,name,args)
  const service=async(name,args)=>{const c=await db.pool.connect();try{await c.query('BEGIN');await c.query('SET LOCAL ROLE service_role');const placeholders=args.map((_,i)=>'$'+(i+1)).join(',');const r=await c.query(`SELECT ${name}(${placeholders}) r`,args);await c.query('COMMIT');return r.rows[0].r}catch(e){await c.query('ROLLBACK');throw e}finally{c.release()}}
  assert.ok((await rpc(admin,'ksc_creator_setup')).some(x=>x.id===exam))
  await assert.rejects(rpc(teacher,'ksc_creator_setup'),/Administrator/)
  await assert.rejects(rpc(teacher,'ksc_creator_begin_create',{p_actor:admin,p_request:request,p_email:'creator@ksc.local',p_name:'Creator',p_exams:[exam]}),/permission denied/)
  await assert.rejects(service('ksc_creator_begin_create',[teacher,request,'creator@ksc.local','Creator',[exam]]),/Administrator/)
  await assert.rejects(service('ksc_creator_begin_create',[admin,request,'creator@ksc.local','Creator',[]]),/valid assigned exams/)
  await service('ksc_creator_begin_create',[admin,request,'creator@ksc.local','Creator',[exam]])
  await assert.rejects(service('ksc_staff_begin_create',[admin,request,'creator@ksc.local','Creator',[],[]]),/Request changed/)
  await db.pool.query("INSERT INTO auth.users(id,email,email_confirmed_at,raw_app_meta_data) VALUES($1,'creator@ksc.local',now(),$2),($3,'existing@ksc.local',now(),'{}')",[creator,{ksc_staff_request:request},existing])
  assert.equal((await service('ksc_staff_complete_create',[admin,request,creator])).created,true)
  assert.equal((await service('ksc_staff_complete_create',[admin,request,creator])).id,creator)
  assert.equal((await rpc(creator,'ksc_my_access')).role,'creator')
  await assert.rejects(rpc(creator,'ksc_my_creator_exams'),/Active creator/)
  assert.equal((await db.pool.query('SELECT * FROM teacher_profiles WHERE id=$1',[creator])).rowCount,0)
  const gate=await service('ksc_staff_password_gate',[creator,creator,false,null])
  await service('ksc_staff_password_complete',[creator,gate.version])
  assert.deepEqual((await rpc(creator,'ksc_my_creator_exams')).map(x=>x.id),[exam])
  const course=await rpc(admin,'ksc_create_course',{p_institute:'00000000-0000-4000-8000-000000000001',p_name:'Teacher course',p_description:''})
  const batch=await rpc(admin,'ksc_create_batch',{p_course:course,p_name:'Teacher batch'})
  // Even stray assignment rows must not turn a creator into teaching staff.
  await db.pool.query('INSERT INTO ksc_teacher_courses VALUES($1,$2)',[creator,course])
  await db.pool.query('INSERT INTO ksc_teacher_batches VALUES($1,$2)',[creator,batch])
  assert.equal(await rpc(creator,'ksc_is_active_staff'),false)
  assert.equal(await rpc(creator,'is_teacher'),false)
  assert.equal(await rpc(creator,'ksc_manages_course',{p_course:course}),false)
  assert.equal(await rpc(creator,'ksc_manages_batch',{p_batch:batch}),false)
  assert.deepEqual(await rpc(creator,'ksc_teaching_results'),[])
  await assert.rejects(rpc(creator,'ksc_staff_paper_save',{p_course:course,p_id:null,p_metadata:{},p_questions:[],p_revision:null}),/Assigned course/)
  await assert.rejects(rpc(creator,'ksc_staff_list'),/Administrator/)
  await assert.rejects(rpc(teacher,'ksc_my_creator_exams'),/Active creator/)
  await assert.rejects(db.runner.asUser(creator,c=>c.query('INSERT INTO ksc_creator_exams VALUES($1,$2)',[creator,exam])),/permission denied/)
  await assert.rejects(rpc(admin,'ksc_creator_assign',{p_user:creator,p_exams:[],p_version:1}),/changed/)
  await assert.rejects(rpc(admin,'ksc_creator_assign',{p_user:creator,p_exams:[randomUUID()],p_version:3}),/valid assigned exams/)
  await rpc(admin,'ksc_creator_assign',{p_user:creator,p_exams:[],p_version:3})
  assert.deepEqual(await rpc(creator,'ksc_my_creator_exams'),[])
  await rpc(admin,'ksc_creator_assign',{p_user:creator,p_exams:[exam],p_version:4})
  await rpc(admin,'ksc_staff_set_state',{p_user:creator,p_state:'suspended',p_version:5})
  await assert.rejects(rpc(creator,'ksc_my_creator_exams'),/Active creator/)
  await rpc(admin,'ksc_staff_set_state',{p_user:creator,p_state:'active',p_version:6})
  const reset=await service('ksc_staff_password_gate',[admin,creator,true,7])
  await service('ksc_staff_password_release',[admin,creator,reset.version])
  await assert.rejects(rpc(creator,'ksc_my_creator_exams'),/Active creator/)
  await service('ksc_staff_password_gate',[creator,creator,false,null]).then(g=>service('ksc_staff_password_complete',[creator,g.version]))
  await rpc(admin,'ksc_creator_grant_existing',{p_user:existing,p_email:'existing@ksc.local',p_name:'Existing creator',p_exams:[exam]})
  assert.equal((await rpc(existing,'ksc_my_access')).role,'creator')
  assert.equal((await rpc(existing,'ksc_my_access')).password_change_required,false)
  assert.equal((await db.pool.query('SELECT raw_app_meta_data FROM auth.users WHERE id=$1',[existing])).rows[0].raw_app_meta_data.ksc_staff_request,undefined)
  await assert.rejects(rpc(admin,'ksc_creator_grant_existing',{p_user:teacher,p_email:'other.teacher@ksc.local',p_name:'Teacher',p_exams:[exam]}),/without staff access/)
  assert.equal((await rpc(admin,'ksc_staff_list')).find(x=>x.id===creator).exams[0],exam)
 }finally{await db.stop()}
})
