// B4.8.4B — packages the B4.8.4A2 learned glyph-cluster table as the versioned legacy-Telugu decoder
// asset (scripts/lib/telugu-legacy-decoder-asset.mjs). Offline tool; no network, no database.
//
// Inputs: reports/b484a2/decoder-table.json (learned from OCR-agreement segments; the benchmark
// reference, the 71 exceptions and live-decided units were held out) and the golden PDF, read ONLY for
// the identity (per-code advance widths) of the embedded fonts the Telugu runs are drawn with.
// Output keeps: font variants (widths), cluster -> akshara entries with count >= 2 and share >= 0.9.
// No sentence, word list, question text or answer is written: every entry is one glyph cluster
// (<= 5 codes) mapped to one orthographic syllable, and the script refuses anything longer.
//
//   node scripts/b484b-build-decoder-asset.mjs
import fs from 'node:fs'
import { buildPageModels } from './lib/pdf-page-model.mjs'
import { analysePaper } from './lib/paper-layout.mjs'
import { buildTeluguStructures } from './lib/telugu-structure.mjs'
import { GOLDEN_PDF } from './lib/local-draft-db.mjs'

const VERSION = '1.0.0'
const MIN_COUNT = 2, MIN_SHARE = 0.9
const OUT = 'scripts/lib/telugu-legacy-decoder-asset.mjs'
const table = JSON.parse(fs.readFileSync('reports/b484a2/decoder-table.json', 'utf8'))

// ---- font identity: the fonts that draw the Telugu runs' private-use glyphs ------------------------
const { pages, fonts } = await buildPageModels(GOLDEN_PDF)
const structures = buildTeluguStructures(pages, analysePaper(pages))
const itemsByPage = new Map(pages.map(p => [p.page, p.items]))
const PUA = /[-]/
const used = new Map(), itemCount = new Map()   // fontName -> Set(code point), number of items
for (const s of structures) for (const u of s.units) for (const l of u.lineRuns) for (const r of l.runs) {
  if (r.type !== 'TE') continue
  const R = r.rect
  for (const i of itemsByPage.get(R.page) || []) {
    if (!PUA.test(i.str) || !(i.x < R.x1 && i.x + (i.width || 0) > R.x0 + 0.5 && i.y >= R.y0 && i.y <= R.y1)) continue
    if (!used.has(i.fontName)) used.set(i.fontName, new Set())
    itemCount.set(i.fontName, (itemCount.get(i.fontName) || 0) + 1)
    for (const ch of i.str) if (PUA.test(ch)) used.get(i.fontName).add(ch.codePointAt(0))
  }
}
const variants = []
for (const [fontName, codes] of [...used].sort((a, b) => itemCount.get(b[0]) - itemCount.get(a[0]))) {
  const f = fonts[fontName]
  if (codes.size < 40) { console.log(`skip ${fontName} (${f?.name}): only ${codes.size} codes used in Telugu runs`); continue }
  if (!f?.glyphs?.length) throw new Error(`no glyph metrics for ${fontName} — open the PDF with fontExtraProperties`)
  const w = new Map(f.glyphs)
  const missing = [...codes].filter(c => !w.has(c))
  if (missing.length) throw new Error(`${fontName}: ${missing.length} used codes without a width`)
  // The face drawing most of the Telugu text is the regular one; the PDF name is recorded beside it.
  variants.push({ id: variants.length ? 'bold' : 'regular', pdfName: f.name, program: f.program, codes: codes.size, items: itemCount.get(fontName), glyphs: f.glyphs })
}
if (variants.length !== 2) throw new Error(`expected the regular and bold legacy fonts, found ${variants.length}`)

// ---- cluster entries ---------------------------------------------------------------------------------
const AKSHARA = /^(?:[క-హౘ-ౚ](?:్[క-హౘ-ౚ])*(?:్)?[ా-ౌౕౖౢౣ]?|[అ-ఔౠౡ]|[ఀ-ః])$/u
const entries = []
for (const e of table.entries) {
  if (!(e.count >= MIN_COUNT && e.share >= MIN_SHARE)) continue
  const codes = e.block.split('.')
  if (codes.length > 5) throw new Error(`cluster too long: ${e.block}`)
  if (!AKSHARA.test(e.akshara)) throw new Error(`entry is not one syllable: ${e.block} -> ${e.akshara}`)
  entries.push([e.block, e.akshara, e.count])
}
entries.sort((a, b) => (a[0] < b[0] ? -1 : a[0] > b[0] ? 1 : 0))

const js = `// GENERATED by scripts/b484b-build-decoder-asset.mjs — do not edit by hand.
// B4.8.4B legacy-Telugu glyph decoder asset, version ${VERSION}.
//
// Bound to ONE embedded legacy Telugu font family/encoding (private-use codes U+F020–U+F0FF, no
// ToUnicode), identified by [code point, advance width] pairs of its regular and bold faces (the width of the glyph
// each private-use character names). Entries map ONE glyph
// cluster (hex low bytes of up to 5 codes, "." separated) to ONE Telugu syllable, with the number of
// OCR-agreement observations it was learned from (B4.8.4A2). No sentences, words, questions or answers.
export const LEGACY_TELUGU_DECODER_ASSET = Object.freeze({
  name: 'ksc-legacy-telugu-decoder',
  version: '${VERSION}',
  encoding: 'legacy-telugu-pua-f0',
  learned: { from: 'reports/b484a2/decoder-table.json', generated: ${JSON.stringify(table.generated)}, minCount: ${MIN_COUNT}, minShare: ${MIN_SHARE} },
  params: Object.freeze({ maxClusterCodes: 5, beam: 6, ambiguityRatio: 20, minFontCodes: 40 }),
  fontVariants: Object.freeze([
${variants.map(v => `    Object.freeze({ id: '${v.id}', pdfName: ${JSON.stringify(v.pdfName)}, program: ${JSON.stringify(v.program)}, glyphs: Object.freeze(${JSON.stringify(v.glyphs)}) }),`).join('\n')}
  ]),
  entries: Object.freeze(${JSON.stringify(entries)}),
})
`
fs.writeFileSync(OUT, js)
console.log(JSON.stringify({ out: OUT, version: VERSION, variants: variants.map(v => ({ id: v.id, pdfName: v.pdfName, program: v.program, codesUsed: v.codes, items: v.items, glyphs: v.glyphs.length })), entries: entries.length }, null, 1))
